import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: 1280, height: 800 } })
await p.addInitScript(() => localStorage.setItem('world-listens.hint', '1'))
await p.goto('http://127.0.0.1:4173/?t=10&fresh')
await p.waitForFunction(() => window.__sims && window.__sims.size > 3, null, { timeout: 120000 })
const T0 = Date.now(); const lap = (m) => console.log(m, ((Date.now() - T0) / 1000).toFixed(1))
const fps = await p.evaluate(() => new Promise((r) => { const f0 = window.__frames; setTimeout(() => r((window.__frames - f0) / 3), 3000) }))
console.log('fps', fps)
await p.evaluate(() => window.__world.getState().setGravity(0))
await p.waitForFunction(() => [...window.__sims.values()].some((s) => s.off.y > 3), null, { timeout: 120000 }); lap('lifted')
await p.evaluate(() => { const s = window.__world.getState(); s.setGravity(-0.6); s.toggleOrbit ? s.toggleOrbit() : window.__world.setState({ orbit: true }) })
await p.waitForTimeout(8000); lap('orbit phase')
await p.evaluate(() => window.__world.getState().restoreRules())
const probe = setInterval(async () => { try { console.log('  ', await p.evaluate(() => { const v = [...window.__sims.entries()]; let w = v.map(([k, s]) => [k, +s.off.y.toFixed(2), +s.off.x.toFixed(2)]).sort((a, b) => Math.abs(b[1]) - Math.abs(a[1])); return JSON.stringify(w.slice(0, 3)) + ' g=' + window.__env.gravity.toFixed(2) })) } catch {} }, 5000)
await p.waitForFunction(() => [...window.__sims.values()].every((s) => Math.abs(s.off.y) < 0.3 && Math.abs(s.off.x) < 0.5), null, { timeout: 240000 }); lap('landed')
clearInterval(probe); await b.close()
